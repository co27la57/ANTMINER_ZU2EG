#!/bin/sh
# =====================================================================
# Boot script for the Antminer E7: bring up the headless X stack and the
# Bad Apple!! demo so that a VNC client sees the xfce4 desktop with the
# video playing.
#
#   Xvfb :1  (1280x800x24)
#     -> x11vnc (exports :1 on TCP 5900, no password)
#       -> xfce4 session (top panel + bottom icon dock)
#         -> mpv playing badapple.mp4
#
# Start manually:   sh /mnt/sd2/start_desktop.sh
# =====================================================================
ROOT=/mnt/sd2/debian
DISP=:1
LOG=/mnt/sd2/desktop.log

echo "" >> "$LOG"
echo "==================== start_desktop: $(date) ====================" >> "$LOG"

# --- mount the SD card (the device node number changes after a re-plug) ---
rm -f /dev/mmcblk0 /dev/mmcblk0p1 /dev/mmcblk0p2 2>/dev/null
grep -E 'mmcblk' /proc/partitions | while read MAJ MIN BLKS NAME; do
    mknod "/dev/$NAME" b "$MAJ" "$MIN" 2>/dev/null && chmod 660 "/dev/$NAME"
done
umount "$ROOT/proc" 2>/dev/null
umount "$ROOT/sys" 2>/dev/null
umount "$ROOT/dev/pts" 2>/dev/null
umount "$ROOT/dev/shm" 2>/dev/null
umount /mnt/sd2 2>/dev/null
sleep 1
mkdir -p /mnt/sd2
for dev in /dev/mmcblk0p1 /dev/mmcblk0p2 /dev/mmcblk0; do
    [ -b "$dev" ] || continue
    mount "$dev" /mnt/sd2 2>/dev/null
    grep -q "^$dev /mnt/sd2 " /proc/mounts 2>/dev/null && break
done

mkdir -p "$ROOT/proc" "$ROOT/sys"
mount --bind /proc "$ROOT/proc" 2>/dev/null
mount --bind /sys  "$ROOT/sys" 2>/dev/null

C() { busybox chroot "$ROOT" /bin/sh -c "$1" 2>&1; }

# --- device nodes inside the chroot ---
mkdir -p "$ROOT/dev/pts" "$ROOT/dev/shm"
for spec in "null c 1 3" "zero c 1 5" "full c 1 7" "random c 1 8" "urandom c 1 9" \
            "tty c 5 0" "console c 5 1" "ptmx c 5 2" "ttyS0 c 4 64" "ttyS1 c 4 65"; do
    NAME=$(echo "$spec" | cut -d' ' -f1); TYPE=$(echo "$spec" | cut -d' ' -f2)
    MAJ=$(echo "$spec" | cut -d' ' -f3);   MIN=$(echo "$spec" | cut -d' ' -f4)
    [ -e "$ROOT/dev/$NAME" ] || mknod "$ROOT/dev/$NAME" "$TYPE" "$MAJ" "$MIN" 2>/dev/null
    chmod 666 "$ROOT/dev/$NAME" 2>/dev/null
done

C 'mount -t devpts devpts /dev/pts 2>/dev/null'
C 'mount -t tmpfs -o size=48M tmpfs /dev/shm 2>/dev/null'

# --- dbus ---
C 'mkdir -p /run/dbus /var/run/dbus'
C 'dbus-daemon --system --fork 2>/dev/null'
sleep 1

# --- MIME database ------------------------------------------------------
# gdk-pixbuf is built with GDK_PIXBUF_USE_GIO_MIME, so it identifies every
# image through GIO's content-type guessing.  That needs the shared-mime-info
# database (/usr/share/mime/magic + mime.cache), which is generated by
# `update-mime-database` in the package postinst.  Because the .deb files
# were unpacked by hand the postinst never ran -> every icon showed up as a
# red "broken image" cross.  Regenerate it here (idempotent, ~10 s).
if [ ! -s "$ROOT/usr/share/mime/magic" ] || [ ! -s "$ROOT/usr/share/mime/mime.cache" ]; then
    echo "generating MIME database ..." >> "$LOG"
    C 'update-mime-database /usr/share/mime' >> "$LOG" 2>&1
fi

# --- icon theme caches --------------------------------------------------
if [ ! -s "$ROOT/usr/share/icons/gnome/icon-theme.cache" ]; then
    C 'gtk-update-icon-cache -f -t /usr/share/icons/gnome' >> "$LOG" 2>&1
fi
if [ ! -s "$ROOT/usr/share/icons/hicolor/icon-theme.cache" ]; then
    C 'gtk-update-icon-cache -f -t /usr/share/icons/hicolor' >> "$LOG" 2>&1
fi

# --- X11 font indexes ---------------------------------------------------
# Xvfb only starts with "built-ins"; generate fonts.dir so we can add the
# bitmap font directories (incl. JIS X 0208 CJK) afterwards.  Without this
# Dillo/FLTK renders Chinese as empty boxes.
for fd in "$ROOT/usr/share/fonts/X11/misc" "$ROOT/usr/share/fonts/X11/75dpi"; do
    if [ -d "$fd" ] && [ ! -f "$fd/fonts.dir" ]; then
        C "mkfontdir ${fd#$ROOT} 2>/dev/null"
    fi
done

# --- Xvfb ---
C 'pkill -9 -f Xvfb 2>/dev/null'
sleep 1
rm -f "$ROOT/tmp/.X1-lock" "$ROOT/tmp/.X11-unix/X1" 2>/dev/null
C "Xvfb $DISP -screen 0 1280x800x24 -ac +extension GLX +extension RANDR -nolisten tcp > /tmp/xvfb.log 2>&1 &"
sleep 8
if ! C 'ls /tmp/.X11-unix/' | grep -q X1; then
    echo "Xvfb failed to start" >> "$LOG"
    C 'cat /tmp/xvfb.log' >> "$LOG"
    exit 1
fi
echo "Xvfb up on $DISP" >> "$LOG"

# add the font paths to the running server (1000+ fonts incl. CJK)
C "export DISPLAY=$DISP; xset +fp /usr/share/fonts/X11/misc 2>/dev/null; \
   xset +fp /usr/share/fonts/X11/75dpi 2>/dev/null; xset fp rehash 2>/dev/null"

# --- x11vnc ---
C 'pkill -9 -f x11vnc 2>/dev/null'
sleep 1
C "x11vnc -display $DISP -auth none -forever -shared -nopw -noxdamage -listen 0.0.0.0 -o /tmp/x11vnc.log > /tmp/x11vnc.out 2>&1 &"
sleep 6
if netstat -lnt 2>/dev/null | grep -q 5900; then
    echo "x11vnc listening on 0.0.0.0:5900" >> "$LOG"
else
    echo "x11vnc failed to bind" >> "$LOG"
    C 'cat /tmp/x11vnc.log' >> "$LOG"
fi

# --- xfce4 session ------------------------------------------------------
# kill leftovers from a previous run, including a stale panel that would
# otherwise refuse to start ("There is already a running instance").
for p in $(pidof xfce4-panel 2>/dev/null); do kill -9 "$p" 2>/dev/null; done
C 'pkill -9 -f xfdesktop 2>/dev/null; pkill -9 -f xfwm4 2>/dev/null; pkill -9 -f xfsettingsd 2>/dev/null; pkill -9 -f mpv 2>/dev/null'
sleep 2
rm -rf "$ROOT/tmp/xdg"; mkdir -p "$ROOT/tmp/xdg"; chmod 700 "$ROOT/tmp/xdg"

ENVSTR="export DISPLAY=$DISP; export HOME=/root; export USER=root; export SHELL=/bin/bash; \
export XDG_RUNTIME_DIR=/tmp/xdg; export XDG_CONFIG_HOME=/root/.config; \
export XDG_CACHE_HOME=/root/.cache; export XDG_DATA_HOME=/root/.local/share; \
export XDG_DATA_DIRS=/usr/local/share:/usr/share; export XDG_CONFIG_DIRS=/etc/xdg; \
export XDG_SESSION_TYPE=x11; export DESKTOP_SESSION=xfce4; export GDK_BACKEND=x11; \
mkdir -p /tmp/xdg; chmod 700 /tmp/xdg;"

C "$ENVSTR xfsettingsd > /tmp/xfsettingsd.log 2>&1 &"
sleep 4
C "$ENVSTR xfdesktop --disable-wm-check > /tmp/xfdesktop.log 2>&1 &"
sleep 4
C "$ENVSTR xfwm4 --replace > /tmp/xfwm4.log 2>&1 &"
sleep 4
C "$ENVSTR xfce4-panel > /tmp/xfce4-panel.log 2>&1 &"
sleep 8
echo "xfce4 session up" >> "$LOG"

# --- Bad Apple!! ---
C 'pkill -9 -f mpv 2>/dev/null; pkill -9 -f badapple 2>/dev/null'
sleep 2
C "nohup /usr/local/bin/badapple --window > /tmp/badapple.log 2>&1 &"
sleep 5
echo "Bad Apple!! launched" >> "$LOG"
C 'ps | grep -E "mpv|mplayer"' >> "$LOG"

# --- Dillo browser (lightweight: ~20 MB, no JS; modern browsers OOM here) ---
C 'pkill -9 -f dillo 2>/dev/null; pkill -9 -f dpid 2>/dev/null'
sleep 1
C "export DISPLAY=$DISP; export HOME=/root; export USER=root; \
export XDG_RUNTIME_DIR=/tmp/xdg; export XDG_DATA_DIRS=/usr/local/share:/usr/share; \
export LD_LIBRARY_PATH=/usr/lib/arm-linux-gnueabihf:/lib/arm-linux-gnueabihf; \
export LANG=zh_CN.UTF-8; \
nohup /usr/bin/dillo -geometry 900x620+330+90 http://www.baidu.com/ \
  > /tmp/dillo.log 2>&1 &"
sleep 8
echo "Dillo browser launched" >> "$LOG"
C 'ps | grep dillo | grep -v grep' >> "$LOG"
echo "==================== desktop ready ====================" >> "$LOG"
